// MARK: - Floot background wake (generated by the Floot build)

final class FlootBackgroundWake {
    static let shared = FlootBackgroundWake()
    static let refreshTaskId = "com.floot.backgroundwake.refresh"
    static let pushMarker = "flootBackground"
    static let budget: TimeInterval = 25

    private weak var plugin: FlootBackgroundWakePlugin?
    private var pendingEvents: [[String: Any]] = []
    private var completions: [String: (Bool) -> Void] = [:]
    private var hasBeenActive = false
    private var registered = false
    // Set when JS was told the launch was a background one, so it can be told
    // to render once the user brings the app to the foreground.
    var reportedBackgroundLaunch = false

    private var refreshPermitted: Bool {
        let ids = Bundle.main.object(forInfoDictionaryKey: "BGTaskSchedulerPermittedIdentifiers") as? [String]
        return ids?.contains(FlootBackgroundWake.refreshTaskId) == true
    }

    func registerAtLaunch() {
        guard !registered else { return }
        registered = true
        let center = NotificationCenter.default
        center.addObserver(forName: UIApplication.didEnterBackgroundNotification, object: nil, queue: .main) { [weak self] _ in
            self?.scheduleRefresh()
        }
        center.addObserver(forName: UIApplication.didBecomeActiveNotification, object: nil, queue: .main) { [weak self] _ in
            self?.becameActive()
        }
        guard refreshPermitted else {
            CAPLog.print("⚡️  Floot background wake: \(FlootBackgroundWake.refreshTaskId) is not in BGTaskSchedulerPermittedIdentifiers; Background App Refresh is off")
            return
        }
        BGTaskScheduler.shared.register(forTaskWithIdentifier: FlootBackgroundWake.refreshTaskId, using: DispatchQueue.main) { [weak self] task in
            guard let self = self, let refresh = task as? BGAppRefreshTask else {
                task.setTaskCompleted(success: false)
                return
            }
            self.handleRefresh(refresh)
        }
    }

    func scheduleRefresh() {
        guard refreshPermitted else { return }
        let request = BGAppRefreshTaskRequest(identifier: FlootBackgroundWake.refreshTaskId)
        request.earliestBeginDate = Date(timeIntervalSinceNow: 15 * 60)
        do {
            try BGTaskScheduler.shared.submit(request)
        } catch {
            CAPLog.print("⚡️  Floot background wake: could not schedule refresh: \(error)")
        }
    }

    private func handleRefresh(_ task: BGAppRefreshTask) {
        scheduleRefresh()
        let id = deliver(reason: "refresh", data: [:]) { ok in
            task.setTaskCompleted(success: ok)
        }
        task.expirationHandler = { [weak self] in
            DispatchQueue.main.async { self?.finish(id: id, failed: true) }
        }
    }

    private func becameActive() {
        hasBeenActive = true
        if reportedBackgroundLaunch {
            reportedBackgroundLaunch = false
            plugin?.emit("foreground", [:])
        }
    }

    /// Main thread only. Returns the wake id.
    @discardableResult
    func deliver(reason: String, data: [String: Any], completion: @escaping (Bool) -> Void) -> String {
        let id = UUID().uuidString
        completions[id] = completion
        let deadline = Date().addingTimeInterval(FlootBackgroundWake.budget)
        let event: [String: Any] = [
            "id": id,
            "reason": reason,
            "data": data,
            "coldStart": !hasBeenActive,
            "deadline": (deadline.timeIntervalSince1970 * 1000).rounded()
        ]
        if let plugin = plugin {
            plugin.emit("wake", event)
        } else {
            pendingEvents.append(event)
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + FlootBackgroundWake.budget) { [weak self] in
            self?.finish(id: id, failed: true)
        }
        return id
    }

    /// Main thread only. Completes a wake once; later calls are no-ops.
    func finish(id: String, failed: Bool) {
        guard let completion = completions.removeValue(forKey: id) else { return }
        completion(!failed)
    }

    func attach(_ plugin: FlootBackgroundWakePlugin) {
        let run = {
            self.plugin = plugin
            let events = self.pendingEvents
            self.pendingEvents.removeAll()
            for event in events {
                plugin.emit("wake", event)
            }
        }
        if Thread.isMainThread { run() } else { DispatchQueue.main.async(execute: run) }
    }

    /// The wake payload of a Floot background push, or nil for any other push.
    static func wakeData(from userInfo: [AnyHashable: Any]) -> [String: Any]? {
        let marker = userInfo[pushMarker]
        let isWake = (marker as? String) == "1" || (marker as? NSNumber)?.boolValue == true
        guard isWake else { return nil }
        guard let raw = userInfo["floot"] as? String,
              let bytes = raw.data(using: .utf8),
              let parsed = try? JSONSerialization.jsonObject(with: bytes) as? [String: Any] else {
            return [:]
        }
        return parsed
    }
}

@objc(FlootBackgroundWakePlugin)
public class FlootBackgroundWakePlugin: CAPPlugin, CAPBridgedPlugin {
    public let identifier = "FlootBackgroundWakePlugin"
    public let jsName = "FlootBackgroundWake"
    public let pluginMethods: [CAPPluginMethod] = [
        CAPPluginMethod(name: "getLaunchState", returnType: CAPPluginReturnPromise),
        CAPPluginMethod(name: "complete", returnType: CAPPluginReturnPromise)
    ]

    @objc override public func load() {
        FlootBackgroundWake.shared.attach(self)
    }

    func emit(_ event: String, _ data: [String: Any]) {
        notifyListeners(event, data: data, retainUntilConsumed: true)
    }

    @objc func getLaunchState(_ call: CAPPluginCall) {
        DispatchQueue.main.async {
            let background = UIApplication.shared.applicationState == .background
            if background {
                FlootBackgroundWake.shared.reportedBackgroundLaunch = true
            }
            call.resolve(["background": background])
        }
    }

    @objc func complete(_ call: CAPPluginCall) {
        let id = call.getString("id") ?? ""
        let failed = call.getBool("failed") ?? false
        if let error = call.getString("error") {
            CAPLog.print("⚡️  onBackgroundWake failed: \(error)")
        }
        DispatchQueue.main.async {
            FlootBackgroundWake.shared.finish(id: id, failed: failed)
        }
        call.resolve()
    }
}
